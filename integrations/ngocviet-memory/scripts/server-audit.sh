#!/usr/bin/env bash
# Phase 0 server audit — READ-ONLY. Run this ON THE REAL TARGET SERVER.
#
# This script does not exist to be run in a sandbox/build session — it was
# written in one, but never executed there, because doing so would only
# describe that sandbox, not your production server. It changes nothing:
# every command below is a read query. It writes one timestamped report
# file and nothing else.
#
# Usage (on the real server):
#   ./scripts/server-audit.sh
#   # then fill the "Risks / conclusion" section of the generated report
#   # by hand and copy it into docs/server-audit-checklist.md yourself —
#   # this script deliberately does not write READY/BLOCKED for you.
set -euo pipefail

OUT_DIR="${AUDIT_OUT_DIR:-./audit-reports}"
mkdir -p "${OUT_DIR}"
STAMP="$(date -u +%Y-%m-%dT%H%M%SZ)"
OUT_FILE="${OUT_DIR}/server-audit-${STAMP}.md"

PORTS_OF_INTEREST=(3000 3080 5432 8000 8080 8090 8888 9000 8077)

{
  echo "# Server Audit Report (raw, unreviewed) — ${STAMP}"
  echo
  echo "Generated by scripts/server-audit.sh. This is raw command output,"
  echo "not a conclusion — a human must review it and fill in"
  echo "docs/server-audit-checklist.md's 'Risks' and 'Conclusion' sections"
  echo "before anything is deployed. No secrets are intentionally printed by"
  echo "this script, but review before sharing this file anywhere."
  echo

  echo "## hostname / uname / os-release"
  echo '```'
  hostname 2>&1 || true
  uname -a 2>&1 || true
  cat /etc/os-release 2>&1 || true
  echo '```'
  echo

  echo "## Docker"
  echo '```'
  docker --version 2>&1 || echo "docker: not found"
  docker compose version 2>&1 || echo "docker compose: not found"
  echo '```'
  echo

  echo "## Resources"
  echo '```'
  echo "-- df -h --"
  df -h 2>&1 || true
  echo "-- free -h --"
  free -h 2>&1 || true
  echo '```'
  echo

  echo "## Current containers"
  echo '```'
  docker ps 2>&1 || echo "docker ps failed (daemon not reachable / no permission)"
  echo "-- all (including stopped) --"
  docker ps -a 2>&1 || true
  echo '```'
  echo

  echo "## Docker networks"
  echo '```'
  docker network ls 2>&1 || true
  echo '```'
  echo

  echo "## Docker volumes"
  echo '```'
  docker volume ls 2>&1 || true
  echo '```'
  echo

  echo "## Listening ports (ss -lntup)"
  echo '```'
  ss -lntup 2>&1 || echo "ss failed — try running as root/sudo"
  echo '```'
  echo

  echo "## Port-of-interest conflict check"
  echo '```'
  for port in "${PORTS_OF_INTEREST[@]}"; do
    hit="$(ss -lntup 2>/dev/null | awk -v p=":${port} " '$0 ~ p' || true)"
    if [[ -n "${hit}" ]]; then
      echo "PORT ${port}: IN USE -> ${hit}"
    else
      echo "PORT ${port}: free"
    fi
  done
  echo '```'
  echo

  echo "## Related service hints (best-effort grep over container names/images)"
  echo '```'
  docker ps -a --format '{{.Names}} | {{.Image}}' 2>&1 | grep -Ei 'hermes|openclaw|odoo|n8n|deepseek|postgres|redis|cloudflared|nginx|traefik|caddy' || echo "none matched (or docker unavailable)"
  echo '```'
  echo

  echo "## Manual follow-ups (this script cannot determine these for you)"
  echo "- [ ] Is any hit above actually Odoo's/n8n's/Hermes'/OpenClaw's production instance?"
  echo "- [ ] Is any disk filesystem above 80% used?"
  echo "- [ ] Does \`ngocviet-memory-net\` or \`ngocviet_mem0_postgres_data\` already exist (name collision)?"
  echo "- [ ] Conclusion: READY or BLOCKED, and why."
} > "${OUT_FILE}"

echo "Wrote ${OUT_FILE}"
echo "Next: review it, then copy the relevant parts into docs/server-audit-checklist.md"
echo "and fill in its Risks/Conclusion sections by hand. Do not deploy until that says READY."
